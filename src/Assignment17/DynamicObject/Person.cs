namespace Assignments
{
    /// <summary>
    /// Represents a person with a name, age, and city.
    /// </summary>
    public class Person
    {
        /// <summary>
        /// Gets or sets the person's name.
        /// </summary>
        /// <value>The name of the person</value>
        public string? Name { get; set; }

        /// <summary>
        /// Gets or sets the person's age.
        /// </summary>
        /// = <value>The age of the person</value>
        public int? Age { get; set; }

        /// <summary>
        /// Gets or sets the city in which the person resides.
        /// </summary>
        /// <value>The city of the person</value>
        public string? City { get; set; }
    }
}