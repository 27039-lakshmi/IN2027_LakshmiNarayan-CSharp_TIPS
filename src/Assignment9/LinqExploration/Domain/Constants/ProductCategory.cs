namespace LinqExploration.Domain.Constants
{
    /// <summary>
    /// Provides predefined product category names used throughout the application.
    /// Centralizing category values helps avoid magic strings and reduces the risk of typos.
    /// </summary>
    public static class ProductCategory
    {
        /// <summary>
        /// Represents the Electronics product category.
        /// </summary>
        public const string Electronics = "Electronics";

        /// <summary>
        /// Represents the Books product category.
        /// </summary>
        public const string Books = "Books";

        /// <summary>
        /// Represents the Furniture product category.
        /// </summary>
        public const string Furniture = "Furniture";

        /// <summary>
        /// Represents the Appliances product category.
        /// </summary>
        public const string Appliances = "Appliances";
    }
}